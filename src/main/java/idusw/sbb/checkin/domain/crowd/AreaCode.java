    /**
     * 이름으로 찾는다. 「부산 해운대구」 · 「해운대구」 · 「해운대」 · 「부산」 모두 받는다.
     * 못 찾으면 null — 부르는 쪽이 「지원하지 않는 지역」이라고 말해야 한다.
     */
    public static Area find(String name) {
        if (name == null || name.isBlank()) return null;
        String k = key(name);

        Area exact = BY_NAME.get(k);
        if (exact != null) return exact;

        Area sido = SIDO_FIRST.get(k);
        if (sido != null) return sido;

        /* 「해운대」처럼 「구」를 뺀 말, 「제주도」처럼 뒤에 붙인 말 */
        for (Map.Entry<String, Area> e : BY_NAME.entrySet()) {
            if (e.getKey().startsWith(k) || k.startsWith(e.getKey())) return e.getValue();
        }
        for (Map.Entry<String, Area> e : SIDO_FIRST.entrySet()) {
            if (k.startsWith(e.getKey()) || e.getKey().startsWith(k)) return e.getValue();
        }
        return null;
    }

    /** 시도 하나의 시군구 전부. 화면의 두 번째 고르기 칸이 쓴다. */
    public static List<Area> sigungus(String sido) {
        String k = key(sido);
        return BY_NAME.values().stream().distinct()
                .filter(a -> key(a.sido()).equals(k))
                .toList();
    }

    /** 집중률 예측이 있는 지역인가. 없는 곳에 「혼잡도 확인 중」을 계속 띄우지 않기 위해. */
    public static boolean hasCrowdData(Area a) {
        return a != null && !"29".equals(a.areaCd()) && !"46".equals(a.areaCd());
    }

